function remember(key, value) { try { localStorage.setItem(key, value); } catch {} }
function applyLanguage(lang) {
 if (!Object.hasOwn(i18n, lang)) lang = 'jp';
 document.documentElement.lang = lang === 'jp' ? 'ja' : lang;
 document.querySelectorAll('[data-i18n]').forEach(el => {
  const value = i18n[lang][el.dataset.i18n];
  if (value !== undefined) el.innerHTML = readingMarkup(value);
 });
 language.value = lang;
 const themeLabels = {jp:'テーマを切り替え',id:'Ganti tema',en:'Switch theme',zh:'切换主题',ko:'테마 전환'};
 themeButton.setAttribute('aria-label', themeLabels[lang]);
 remember('profileLang', lang);
}
// Each new visit opens in Japanese, independent of the old profile language.
