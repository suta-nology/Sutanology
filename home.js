// Only authored translation strings are interpreted as ruby markup.
function readingMarkup(text) {
 const escaped = text.replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
 return escaped.replace(/\{([^|{}]+)\|([^{}]+)\}/g, '<ruby>$1<rp>（</rp><rt>$2</rt><rp>）</rp></ruby>');
}
